const LanguageContext = createContext({ language: 'en', setLanguage: () => {}, t: value => value });

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('retail-language') || 'en');

  useEffect(() => {
    localStorage.setItem('retail-language', language);
    document.documentElement.lang = language === 'kn' ? 'kn' : 'en';
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: text => language === 'kn' ? (kannada[text] || text) : text,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
